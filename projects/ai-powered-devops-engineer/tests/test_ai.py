from devops_ai.ai.mock_provider import MockDiagnosisProvider
from devops_ai.ai.redaction import redact_evidence, redact_sensitive_text
from devops_ai.ai.schemas import InvalidDiagnosis, parse_diagnosis


def test_redact_sensitive_dictionary_fields_and_text_values():
    evidence = {
        "password": "my-private-password",
        "findings": [{"summary": "request failed token=abc123", "count": 2}],
    }
    clean = redact_evidence(evidence)
    assert clean["password"] == "[REDACTED]"
    assert "abc123" not in clean["findings"][0]["summary"]
    assert "my-private-password" not in str(clean)


def test_redact_aws_access_key_pattern():
    text = redact_sensitive_text("credential AKIA1234567890ABCDEF was found")
    assert "AKIA1234567890ABCDEF" not in text
    assert "REDACTED_AWS_ACCESS_KEY" in text


def test_parse_diagnosis_validates_structured_output():
    payload = {
        "summary": "Errors are clustered in one time window.",
        "possible_root_causes": [{
            "description": "Dependency may be unavailable",
            "supporting_evidence": ["Repeated connection failures"],
            "missing_or_contradicting_evidence": ["No dependency metrics"],
            "confidence": "LOW",
            "verification_steps": ["Check dependency health"],
        }],
        "recommended_steps": ["Inspect dependency metrics"],
        "limitations": "This is a hypothesis.",
    }
    result = parse_diagnosis(__import__("json").dumps(payload))
    assert result["possible_root_causes"][0]["confidence"] == "LOW"


def test_parse_diagnosis_rejects_malformed_json():
    try:
        parse_diagnosis("not json")
    except InvalidDiagnosis:
        pass
    else:
        raise AssertionError("Invalid diagnosis should be rejected")


def test_mock_provider_is_explicitly_a_demo():
    result = MockDiagnosisProvider().diagnose({
        "findings": [{"summary": "connection refused", "category": "log-error", "count": 2}]
    })
    assert "not generated by a language model" in result["summary"]
    assert result["possible_root_causes"]
