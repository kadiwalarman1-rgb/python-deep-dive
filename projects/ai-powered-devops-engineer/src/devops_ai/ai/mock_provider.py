"""Offline demo provider; it does not call or simulate a real language model."""

from __future__ import annotations

from typing import Any


class MockDiagnosisProvider:
    name = "offline-demo-provider"

    def diagnose(self, evidence: dict[str, Any]) -> dict[str, Any]:
        hypotheses = []
        for finding in evidence.get("findings", [])[:5]:
            summary = str(finding.get("summary", "Unspecified signal"))[:300]
            hypotheses.append(
                {
                    "description": f"Investigate whether this observed signal relates to the incident: {summary}",
                    "supporting_evidence": [
                        f"Rule-based finding category: {finding.get('category', 'unknown')}",
                        f"Observed count: {finding.get('count', 0)}",
                    ],
                    "missing_or_contradicting_evidence": [
                        "No dependency metrics or traces were provided to verify causality."
                    ],
                    "confidence": "LOW",
                    "verification_steps": [
                        "Correlate this time window with application and dependency metrics.",
                        "Inspect traces and deployment changes before concluding root cause.",
                    ],
                }
            )
        return {
            "summary": (
                "Offline demonstration output built from rule-based findings. "
                "This is not generated by a language model and does not establish root cause."
            ),
            "possible_root_causes": hypotheses,
            "recommended_steps": [
                "Confirm timestamps and affected service in the original system.",
                "Correlate findings with deployment, dependency, and infrastructure metrics.",
                "Verify each hypothesis before taking remediation action.",
            ],
            "limitations": "Offline demo provider; no model inference or external call occurred.",
        }
